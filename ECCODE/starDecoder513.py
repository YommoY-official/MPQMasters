# 9. U†EU COMPUTATION
# ============================================================

def compute_logical_channel(U, U_dag, exrec_kraus):
    """
    Compute U†EU for each Kraus operator of the exRec.

    For each Kraus operator K of the exRec:
      K_logical = U · K · U†

    This gives a 32×32 matrix in the (logical, syndrome) basis.
    The 2×2 block at row-block s_out, column-block s_in gives
    the logical transformation conditioned on:
      - incoming syndrome s_in
      - outgoing syndrome s_out

    Ref: Gottesman §14.4.3, Eq. (14.27)
    """
    logical_kraus = []
    for K in exrec_kraus:
        K_logical = U @ K @ U_dag
        logical_kraus.append(K_logical)
    return logical_kraus


def extract_logical_channel_block(logical_kraus, s_in, s_out):
    """
    Extract the 2×2 logical channel block for given syndrome transition.

    Returns the channel as a list of 2×2 Kraus operators.
    The logical channel is: ρ_L -> Σ_k  M_k ρ_L M_k†
    where M_k is the 2×2 block of the k-th logical Kraus operator.
    """
    blocks = []
    for K_L in logical_kraus:
        block = K_L[2 * s_out:2 * s_out + 2, 2 * s_in:2 * s_in + 2]
        blocks.append(block)
    return blocks


def logical_pauli_channel_coefficients(logical_kraus, s_in, s_out):
    """
    Decompose the syndrome-conditioned logical channel into Pauli coefficients.

    For a Pauli channel on a single qubit:
      ρ -> p_I ρ + p_X XρX + p_Y YρY + p_Z ZρZ

    The coefficients are found by:
      p_P = Σ_k |Tr(P · M_k)|² / 4   (for each Pauli P)

    Actually, more carefully: the Choi matrix of the channel determines everything.
    For a single-qubit channel with Kraus ops {M_k}:
      χ_{PQ} = Σ_k Tr(P M_k) Tr(Q M_k)* / 4

    For a Pauli channel, χ is diagonal in the Pauli basis.
    """
    blocks = extract_logical_channel_block(logical_kraus, s_in, s_out)

    paulis = [I2, X, Y, Z]
    pauli_names = ['I', 'X', 'Y', 'Z']

    # Process matrix χ_{PQ} = Σ_k Tr(P · M_k) · Tr(Q · M_k)* / 4
    chi = np.zeros((4, 4), dtype=complex)
    for M in blocks:
        coeffs = np.array([np.trace(P @ M) for P in paulis])  # length 4
        chi += np.outer(coeffs, coeffs.conj()) / 4.0

    # For a Pauli channel, the diagonal gives the Pauli error probabilities
    p_coeffs = {pauli_names[i]: np.real(chi[i, i]) for i in range(4)}

    return p_coeffs, chi


