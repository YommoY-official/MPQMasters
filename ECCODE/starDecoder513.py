"""
Star-decoder and U†EU computation for the [[5,1,3]] perfect quantum code.

This script implements:
1. Construction of the ∗-decoder U as a 32×32 unitary: C^32 -> C^2 ⊗ C^16
2. Abstract EC model (perfect syndrome projection + deterministic Pauli correction)
3. Encoded wait gadget with independent depolarizing noise
4. U†EU computation for the full exRec (FTEC - wait - FTEC)
5. Extraction of syndrome-conditioned logical error channels
6. Verification against case-by-case Pauli error analysis

Reference: Gottesman, "Surviving as a Quantum Computer in a Classical World" (2024),
           §14.4.2-14.4.3 (∗-decoder, Eq. 14.27), §10.2.4 (FTEC definitions),
           Table 3.2 (five-qubit code generators), Table 3.4 (logical Paulis).
"""

import numpy as np
from itertools import product as iterproduct
from functools import reduce

# ============================================================
# 1. PAULI INFRASTRUCTURE
# ============================================================

I2 = np.eye(2, dtype=complex)
X = np.array([[0, 1], [1, 0]], dtype=complex)
Y = np.array([[0, -1j], [1j, 0]], dtype=complex)
Z = np.array([[1, 0], [0, -1]], dtype=complex)

PAULIS_1Q = {'I': I2, 'X': X, 'Y': Y, 'Z': Z}


def kron_list(ops):
    """Tensor product of a list of matrices."""
    return reduce(np.kron, ops)


def pauli_from_string(s):
    """Build n-qubit Pauli from string like 'XZZXI'."""
    return kron_list([PAULIS_1Q[c] for c in s])


# ============================================================
# 2. [[5,1,3]] CODE DEFINITION
# ============================================================

# Stabilizer generators (Gottesman Table 3.2)
STAB_STRINGS = ['XZZXI', 'IXZZX', 'XIXZZ', 'ZXIXZ']
STAB_GENS = [pauli_from_string(s) for s in STAB_STRINGS]

# Logical Paulis (Gottesman Table 3.4)
XBAR_STRING = 'XXXXX'
ZBAR_STRING = 'ZZZZZ'
X_BAR = pauli_from_string(XBAR_STRING)
Z_BAR = pauli_from_string(ZBAR_STRING)

N = 5  # physical qubits
DIM = 2 ** N  # = 32


# ============================================================
# 3. CODESPACE PROJECTOR AND LOGICAL BASIS
# ============================================================

def build_codespace_projector(generators):
    """
    Build Π = (1/2^r) * Σ_{M ∈ S} M
    where S is the full stabilizer group generated by the generators.
    Equivalently: Π = Π_i (I + g_i)/2
    """
    Pi = np.eye(DIM, dtype=complex)
    for g in generators:
        Pi = Pi @ (np.eye(DIM, dtype=complex) + g) / 2.0
    return Pi


def find_codespace_basis(Pi):
    """
    Find orthonormal basis {|0̄⟩, |1̄⟩} for the codespace.
    We diagonalize Π and pick the two eigenvectors with eigenvalue 1.
    Then choose the basis so that Z̄|0̄⟩ = |0̄⟩ and Z̄|1̄⟩ = -|1̄⟩.
    """
    evals, evecs = np.linalg.eigh(Pi)
    # Pick eigenvectors with eigenvalue ≈ 1
    codespace_idx = np.where(np.abs(evals - 1.0) < 1e-10)[0]
    assert len(codespace_idx) == 2, f"Expected 2-dim codespace, got {len(codespace_idx)}"

    # Raw basis vectors
    v0 = evecs[:, codespace_idx[0]]
    v1 = evecs[:, codespace_idx[1]]

    # Diagonalize Z̄ within the codespace to get |0̄⟩, |1̄⟩
    Z_block = np.array([
        [v0.conj() @ Z_BAR @ v0, v0.conj() @ Z_BAR @ v1],
        [v1.conj() @ Z_BAR @ v0, v1.conj() @ Z_BAR @ v1]
    ])
    z_evals, z_evecs = np.linalg.eigh(Z_block)

    # Sort so |0̄⟩ has Z̄ eigenvalue +1, |1̄⟩ has -1
    idx_sort = np.argsort(-z_evals.real)  # +1 first
    z_evecs = z_evecs[:, idx_sort]

    cbar0 = v0 * z_evecs[0, 0] + v1 * z_evecs[1, 0]
    cbar1 = v0 * z_evecs[0, 1] + v1 * z_evecs[1, 1]

    # Normalize
    cbar0 /= np.linalg.norm(cbar0)
    cbar1 /= np.linalg.norm(cbar1)

    return cbar0, cbar1


# ============================================================
# 4. SYNDROME COMPUTATION AND REPRESENTATIVE MAP
# ============================================================

def syndrome_of(pauli_op, generators):
    """
    Compute the 4-bit syndrome of a Pauli operator.
    Syndrome bit i = 0 if pauli_op commutes with generators[i], else 1.
    Returns an integer 0..15.
    """
    bits = []
    for g in generators:
        # Check commutation: gP = Pg (commutes) or gP = -Pg (anticommutes)
        comm = g @ pauli_op - pauli_op @ g
        if np.allclose(comm, 0):
            bits.append(0)
        else:
            bits.append(1)
    return sum(b << (3 - i) for i, b in enumerate(bits))


def build_syndrome_representatives(generators):
    """
    Build a map: syndrome (int) -> representative Pauli (32×32 matrix).

    For the [[5,1,3]] perfect code, the 15 single-qubit errors
    {X_i, Y_i, Z_i : i=1..5} give all 15 nontrivial syndromes,
    and I gives syndrome 0. This exhausts all 16 syndromes.
    """
    syn_rep = {}
    syn_rep_labels = {}

    # Syndrome 0 -> Identity
    syn_rep[0] = np.eye(DIM, dtype=complex)
    syn_rep_labels[0] = 'I'

    for qubit in range(N):
        for name in ['X', 'Y', 'Z']:
            ops = [I2] * N
            ops[qubit] = PAULIS_1Q[name]
            E = kron_list(ops)
            s = syndrome_of(E, generators)
            if s not in syn_rep:
                syn_rep[s] = E
                syn_rep_labels[s] = f'{name}{qubit + 1}'

    assert len(syn_rep) == 16, f"Expected 16 syndrome reps, got {len(syn_rep)}"
    return syn_rep, syn_rep_labels


# ============================================================
# 5. STAR-DECODER CONSTRUCTION
# ============================================================

def build_star_decoder(cbar0, cbar1, syn_rep):
    """
    Build the ∗-decoder U as a 32×32 unitary.

    U : physical Hilbert space C^32 -> C^2 (logical) ⊗ C^16 (syndrome)

    Convention: basis of the output space is |ψ⟩|s⟩ where
      ψ ∈ {0, 1} (logical qubit)
      s ∈ {0, 1, ..., 15} (syndrome)

    Column ordering of U†: column index = 2*s + ψ
    (syndrome runs slow, logical runs fast)

    U† |ψ⟩|s⟩ = E_s |ψ̄⟩

    Ref: Gottesman §14.4.2, Eq. (14.19)
    """
    U_dag = np.zeros((DIM, DIM), dtype=complex)

    for s in range(16):
        E_s = syn_rep[s]
        U_dag[:, 2 * s + 0] = E_s @ cbar0  # |0⟩|s⟩ -> E_s|0̄⟩
        U_dag[:, 2 * s + 1] = E_s @ cbar1  # |1⟩|s⟩ -> E_s|1̄⟩

    # Verify unitarity
    check = U_dag.conj().T @ U_dag
    assert np.allclose(check, np.eye(DIM)), "U† is not unitary!"

    U = U_dag.conj().T  # U = (U†)†
    return U, U_dag


# ============================================================
# 6. ABSTRACT EC MODEL
# ============================================================

def abstract_EC(state_vec):
    """
    Abstract (ideal) error correction:
    1. Project onto syndrome eigenspace (= measure syndrome perfectly)
    2. Apply the correction Pauli for that syndrome
    3. Result: state is projected back into the codespace with syndrome 0

    This implements perfect EC as a CP map on state vectors.
    For a density matrix, you'd sum over syndromes; here we do it
    for a single state vector and return the corrected state + measured syndrome.

    NOTE: In the abstract model, this ALWAYS resets syndrome to 0,
    which is why it kills syndrome memory and makes logical errors
    syndrome-independent. (Gottesman §14.4.2)
    """
    # Build syndrome projectors
    results = []
    for s in range(16):
        # Projector onto syndrome-s subspace
        P_s = np.zeros((DIM, DIM), dtype=complex)
        for bits in iterproduct([0, 1], repeat=4):
            sign = np.eye(DIM, dtype=complex)
            for i, b in enumerate(bits):
                if b == 0:
                    sign = sign @ (np.eye(DIM, dtype=complex) + STAB_GENS[i]) / 2
                else:
                    sign = sign @ (np.eye(DIM, dtype=complex) - STAB_GENS[i]) / 2
            if tuple(bits) == tuple((s >> (3 - i)) & 1 for i in range(4)):
                P_s += sign

        projected = P_s @ state_vec
        prob = np.real(projected.conj() @ projected)
        if prob > 1e-15:
            results.append((s, prob, projected))

    return results


def build_syndrome_projectors():
    """Build all 16 syndrome projectors for the [[5,1,3]] code."""
    projectors = {}
    for s in range(16):
        # Syndrome s has bit pattern: bit i = (s >> (3-i)) & 1
        P_s = np.eye(DIM, dtype=complex)
        for i in range(4):
            bit = (s >> (3 - i)) & 1
            if bit == 0:
                P_s = P_s @ (np.eye(DIM, dtype=complex) + STAB_GENS[i]) / 2
            else:
                P_s = P_s @ (np.eye(DIM, dtype=complex) - STAB_GENS[i]) / 2
        projectors[s] = P_s
    return projectors


def abstract_EC_operator(syn_projectors, syn_rep):
    """
    Build the abstract EC as a single 32×32 operator (for no-fault case):

    EC = Σ_s  E_s†  P_s

    This projects onto the syndrome-s subspace, then applies correction E_s†.
    The result is always in the codespace (syndrome 0).

    This is a sum of orthogonal terms, so it's a valid (unnormalized) operator
    on state vectors. On density matrices: EC(ρ) = Σ_s E_s† P_s ρ P_s E_s
    """
    EC = np.zeros((DIM, DIM), dtype=complex)
    for s in range(16):
        E_s = syn_rep[s]
        P_s = syn_projectors[s]
        EC += E_s.conj().T @ P_s
    return EC


