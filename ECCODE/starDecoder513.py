# 7. DEPOLARIZING NOISE
# ============================================================

def depolarizing_kraus(p):
    """
    Independent single-qubit depolarizing channel on all 5 qubits.

    Single-qubit channel: ρ -> (1-p)ρ + (p/3)(XρX + YρY + ZρZ)

    Kraus operators for single qubit:
      sqrt(1-p) I,  sqrt(p/3) X,  sqrt(p/3) Y,  sqrt(p/3) Z

    For 5 qubits (independent): tensor product of single-qubit Kraus ops.
    Total: 4^5 = 1024 Kraus operators.
    """
    coeffs_1q = {
        'I': np.sqrt(1 - p),
        'X': np.sqrt(p / 3),
        'Y': np.sqrt(p / 3),
        'Z': np.sqrt(p / 3),
    }

    kraus_ops = []
    labels = []
    pauli_names = ['I', 'X', 'Y', 'Z']

    for combo in iterproduct(pauli_names, repeat=N):
        coeff = 1.0
        ops = []
        for c in combo:
            coeff *= coeffs_1q[c]
            ops.append(PAULIS_1Q[c])
        K = coeff * kron_list(ops)
        kraus_ops.append(K)
        labels.append(''.join(combo))

    return kraus_ops, labels


# ============================================================
# 8. FULL exRec ACTION: FTEC - WAIT - FTEC (abstract EC)
# ============================================================

def build_exrec_action_abstract(p, syn_projectors, syn_rep):
    """
    Build the exRec action E as a quantum channel (list of Kraus operators)
    for the circuit:  FTEC_ideal - (depolarizing wait) - FTEC_ideal

    In the ABSTRACT EC model:
    - FTEC is faultless (no noise in EC itself)
    - EC perfectly measures syndrome and applies correction
    - Noise only occurs during the wait step (depolarizing on all 5 qubits)

    The exRec action on a density matrix ρ is:
      E(ρ) = EC · N(ρ) · EC†
    where N is the depolarizing channel during the wait.

    More precisely, the Kraus operators of the full exRec are:
      {EC_trailing · K_noise · EC_leading}  for each noise Kraus K_noise

    But since EC_leading just projects to codespace (no fault),
    and EC_trailing projects back, the effective Kraus ops are:
      {EC · K · EC}  where EC = Σ_s E_s† P_s

    IMPORTANT: In this abstract model, each EC resets syndrome to 0.
    Therefore the logical errors will be syndrome-INDEPENDENT.
    To see syndrome-dependent (non-Markovian) structure, you need
    the realistic fault model.
    """
    EC = abstract_EC_operator(syn_projectors, syn_rep)
    noise_kraus, noise_labels = depolarizing_kraus(p)

    exrec_kraus = []
    exrec_labels = []
    for K, label in zip(noise_kraus, noise_labels):
        # Full exRec Kraus: EC_trailing · K · EC_leading
        kraus = EC @ K @ EC
        exrec_kraus.append(kraus)
        exrec_labels.append(label)

    return exrec_kraus, exrec_labels


